def main():
    html = fixture_html()
    fd, path = tempfile.mkstemp(suffix='.html', dir=ROOT)
    os.close(fd)
    open(path, 'w', encoding='utf-8').write(html)
    try:
        if not os.path.isfile(CHROME):
            print('Chrome not found at', CHROME)
            return 2
        r = subprocess.run(
            [CHROME, '--headless', '--disable-gpu', '--no-sandbox',
             '--virtual-time-budget=9000', '--dump-dom',
             'file:///' + path.replace('\\', '/')],
            capture_output=True, text=True, timeout=90)
        dom = r.stdout
        m = re.search(r'<pre id="__report">(.*?)</pre>', dom, re.S)
        if not m:
            print('FAIL: no report found. Chrome stderr:', r.stderr[-400:])
            return 2
        results = json.loads(m.group(1).replace('&quot;', '"'))
    finally:
        try: os.remove(path)
        except Exception: pass

    failed = 0
    print('%-20s %-24s %-24s %s' % ('FIELD', 'EXPECTED', 'ACTUAL', 'RESULT'))
    print('-' * 78)
    for item in results:
        ok = item['ok']
        if not ok:
            failed += 1
        print('%-20s %-24s %-24s %s' %
              (item['name'], item['expected'][:24], str(item['actual'])[:24],
               'PASS' if ok else 'FAIL'))
    print('-' * 78)
    print('%d/%d fields correct' % (len(results) - failed, len(results)))
    return 0 if failed == 0 else 1


if __name__ == '__main__':
    sys.exit(main())
