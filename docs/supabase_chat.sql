-- LibSyncStudent General Chat — Supabase table setup
-- Run this in the Supabase SQL Editor, then paste the Project URL and
-- anon key into Settings → COMMUNITY CHAT.

create table if not exists public.app_messages (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  text text not null,
  user_name text not null,
  user_id text not null
);

alter table public.app_messages enable row level security;

-- Students can read all messages.
create policy "chat_read"
on public.app_messages for select
to anon
using (true);

-- Students can post messages.
-- Note: with only the anon key, anyone with the key can post. Add auth or
-- rate limiting later if spam becomes a problem.
create policy "chat_insert"
on public.app_messages for insert
to anon
with check (true);

