                backgroundColor: hoverBg,
                foregroundColor: hoverFg,
              ),
              child: _saving
                  ? const SizedBox(
                      width: 20,
                      height: 20,
                      child: CircularProgressIndicator(
                          strokeWidth: 2, color: AppColors.primary),
                    )
                  : Text(_currentPage < 5 ? 'Next' : 'Finish'),
            ),
          ),
          if (_currentPage >= 2) ...[const SizedBox(width: 6), _starButton()],
          ],
          ),
        ],
      ),
    );
  }

