  static Future<String?> _showSearchablePicker(BuildContext context, {
    required String title,
    required List<String> options,
    String? initialValue,
    String? Function(String)? displayTransformer,
  }) {
    return showDialog<String>(
      context: context,
      builder: (ctx) {
        final searchCtrl = TextEditingController(text: initialValue);
        final searchNode = FocusNode();
        String? selected = initialValue;
        return StatefulBuilder(
          builder: (ctx, setDialogState) {
            final filtered = options.where((o) {
              final q = searchCtrl.text.toLowerCase();
              if (q.isEmpty) return true;
              return o.toLowerCase().contains(q);
            }).toList();
            return Dialog(
              backgroundColor: AppColors.surface,
              insetPadding: const EdgeInsets.symmetric(horizontal: 11, vertical: 28),
              shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(11)),
              child: Column(
                mainAxisSize: MainAxisSize.min,
                children: [
                  Padding(
                    padding: const EdgeInsets.fromLTRB(16, 16, 16, 8),
                    child: TextField(
                      controller: searchCtrl,
                      focusNode: searchNode,
                      autofocus: true,
                      decoration: InputDecoration(
                        hintText: 'Search $title...',
                        prefixIcon: StarIcon(Icons.search),
                        suffixIcon: searchCtrl.text.isNotEmpty
                            ? IconButton(
                                icon: const Icon(Icons.clear, size: 18),
                                onPressed: () {
                                  searchCtrl.clear();
                                  setDialogState(() {});
                                },
                              )
                            : null,
                      ),
                      onChanged: (_) => setDialogState(() {}),
                    ),
                  ),
                  const Divider(height: 1),
                  if (filtered.isEmpty)
                    const Padding(
                      padding: EdgeInsets.all(22),
                      child: Text('No results found', style: TextStyle(color: AppColors.textMuted)),
                    )
                  else
                    Flexible(
                      child: ListView.builder(
                        shrinkWrap: true,
                        itemCount: filtered.length,
                        padding: const EdgeInsets.symmetric(vertical: 4),
                        itemBuilder: (_, i) {
                          final item = filtered[i];
                          final display = displayTransformer?.call(item) ?? item;
                          return ListTile(
                            dense: true,
                            selected: selected == item,
                            selectedTileColor: AppColors.primary.withValues(alpha: 0.08),
                            title: Text(display, style: const TextStyle(fontSize: 10, color: AppColors.textPrimary)),
                            onTap: () {
                              Navigator.pop(ctx, item);
                            },
                          );
                        },
                      ),
                    ),
                ],
              ),
            );
          },
        );
      },
    );
  }

